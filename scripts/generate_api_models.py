"""Generates src/judgeval/internal/api/models.py from the committed public spec.

The spec (openapi/public-api.json, copied from judgment-mono's
packages/shared/public-api/openapi.json) inlines every schema and marks shared
ones with `$id`. This hoists those into components so datamodel-codegen emits
them as named TypedDicts, e.g. `ExampleEvaluationRun`.

    uv run python scripts/generate_api_models.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "public-api.json"
OUTPUT = ROOT / "src" / "judgeval" / "internal" / "api" / "models.py"


def hoist_named_schemas(spec: dict[str, Any]) -> dict[str, Any]:
    named: dict[str, Any] = {}

    def hoist(node: Any) -> Any:
        if isinstance(node, list):
            return [hoist(item) for item in node]
        if not isinstance(node, dict):
            return node
        node = {key: hoist(value) for key, value in node.items()}
        name = node.pop("$id", None)
        if not isinstance(name, str):
            return node
        named.setdefault(name, node)
        return {"$ref": f"#/components/schemas/{name}"}

    paths = hoist(spec["paths"])
    existing = hoist(spec.get("components", {}).get("schemas", {}))
    return {
        **spec,
        "paths": paths,
        "components": {"schemas": {**existing, **named}},
    }


def main() -> None:
    spec = hoist_named_schemas(json.loads(SPEC.read_text()))
    with tempfile.NamedTemporaryFile("w", suffix=".json") as hoisted:
        json.dump(spec, hoisted)
        hoisted.flush()
        subprocess.run(
            [
                "datamodel-codegen",
                "--input",
                hoisted.name,
                "--input-file-type",
                "openapi",
                "--output",
                str(OUTPUT),
                "--output-model-type",
                "typing.TypedDict",
                "--target-python-version",
                "3.10",
                "--use-standard-collections",
                "--use-union-operator",
                # Inline schemas are named after their parent so they never
                # take a shared schema's name (e.g. `Example`).
                "--naming-strategy",
                "full-path",
                "--formatters",
                "ruff-format",
                "--disable-timestamp",
                "--custom-file-header",
                "# Generated by scripts/generate_api_models.py from openapi/public-api.json.\n# DO NOT EDIT MANUALLY",
            ],
            check=True,
        )


if __name__ == "__main__":
    sys.exit(main())
