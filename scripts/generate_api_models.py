"""Generates src/judgeval/internal/api/models.py and src/judgeval/api.py from the
committed public spec.

The spec (openapi/public-api.json, copied from judgment-mono's
packages/shared/public-api/openapi.json) lists its named schemas under
`components.schemas`; datamodel-codegen emits one TypedDict per entry, e.g.
`ExampleEvaluationRun`. Request and response bodies written inline on a route
have no name, so they would get no model; for each MCP-backed (`x-mcp`) route
we name them after its MCP tool first, e.g. `CreateJudgeRequest`.

api.py gets one JudgmentApiClient method per `x-mcp` route, named after its
MCP tool (e.g. `list_judges`).

    uv run python scripts/generate_api_models.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "public-api.json"
OUTPUT = ROOT / "src" / "judgeval" / "internal" / "api" / "models.py"
CLIENT_OUTPUT = ROOT / "src" / "judgeval" / "api.py"
HEADER = "# Generated by scripts/generate_api_models.py from openapi/public-api.json.\n# DO NOT EDIT MANUALLY"
QUERY_TYPES = {"integer": "int", "number": "float", "boolean": "bool"}


def name_inline_bodies(spec: dict[str, Any]) -> dict[str, Any]:
    """Gives each x-mcp route's unnamed request and response bodies a model name.

    A body written inline on the route is added to the named schemas as
    `<ToolName>Request` / `<ToolName>Response` (e.g. `create_judge` ->
    `CreateJudgeRequest`), and the route points to it, so datamodel-codegen
    emits a TypedDict for it. Bodies that already reference a named schema
    are left alone."""
    schemas = spec["components"]["schemas"]
    for operations in spec["paths"].values():
        for op in operations.values():
            if not isinstance(op, dict) or "x-mcp" not in op:
                continue
            tool = op["x-mcp"]["tool"].title().replace("_", "")
            bodies = {
                "Request": op.get("requestBody", {}),
                "Response": op["responses"].get("200", {}),
            }
            for suffix, body in bodies.items():
                content = body.get("content", {}).get("application/json")
                if content is None or "$ref" in content["schema"]:
                    continue
                name = tool + suffix
                if name in schemas:
                    raise SystemExit(f"{name} is already in components.schemas")
                schemas[name] = content["schema"]
                content["schema"] = {"$ref": f"#/components/schemas/{name}"}
    return spec


def snake_case(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def model_name(content: dict[str, Any], models: set[str]) -> str:
    name = content["schema"]["$ref"].rsplit("/", 1)[-1]
    models.add(name)
    return name


def render_method(path: str, method: str, op: dict[str, Any], models: set[str]) -> str:
    params = op.get("parameters", [])
    path_params = [p["name"] for p in params if p["in"] == "path"]
    query = [p for p in params if p["in"] == "query"]
    body = op.get("requestBody", {}).get("content", {}).get("application/json")
    response = op["responses"]["200"]["content"]["application/json"]

    args = ["self", *(f"{snake_case(name)}: str" for name in path_params)]
    if body:
        args.append(f"payload: {model_name(body, models)}")
    if query:
        args.append("*")
    for p in sorted(query, key=lambda p: not p.get("required")):
        type_ = QUERY_TYPES.get(p["schema"].get("type"), "str")
        args.append(
            f"{p['name']}: {type_}"
            if p.get("required")
            else f"{p['name']}: {type_} | None = None"
        )
    url = re.sub(
        r"\{(\w+)\}", lambda m: "{encode_path_segment(" + snake_case(m[1]) + ")}", path
    )
    params_arg = "{" + ", ".join(f'"{p["name"]}": {p["name"]}' for p in query) + "}"
    return f'''
    def {op["x-mcp"]["tool"]}({", ".join(args)}) -> {model_name(response, models)}:
        """{op["summary"]} (`{method.upper()} {path}`)."""
        return self._request(
            "{method.upper()}",
            url_for({"f" if "{" in url else ""}"{url}", self.base_url),
            {"payload" if body else "{}"},
            {f"_drop_none({params_arg})" if query else "None"},
        )
'''


def render_client(spec: dict[str, Any]) -> str:
    models: set[str] = set()
    methods = "".join(
        render_method(path, method, op, models)
        for path, operations in spec["paths"].items()
        for method, op in operations.items()
        if "x-mcp" in op
    )
    return f'''{HEADER}
# mypy: disable-error-code="no-any-return"
"""Client for the public /v1 API: one method per Judgment MCP tool."""

from __future__ import annotations

from typing import Any

from judgeval.internal.api.api_client import JudgmentSyncClient
from judgeval.internal.api.models import {", ".join(sorted(models))}
from judgeval.utils.url import encode_path_segment, url_for


def _drop_none(params: dict[str, Any]) -> dict[str, Any]:
    return {{key: value for key, value in params.items() if value is not None}}


class JudgmentApiClient(JudgmentSyncClient):
    __slots__ = ()
{methods}

__all__ = ["JudgmentApiClient"]
'''


def main() -> None:
    spec = name_inline_bodies(json.loads(SPEC.read_text()))
    with tempfile.NamedTemporaryFile("w", suffix=".json") as named:
        json.dump(spec, named)
        named.flush()
        subprocess.run(
            [
                "datamodel-codegen",
                "--input",
                named.name,
                "--input-file-type",
                "openapi",
                "--output",
                str(OUTPUT),
                "--output-model-type",
                "typing.TypedDict",
                "--target-python-version",
                "3.10",
                "--use-standard-collections",
                "--use-union-operator",
                # Inline schemas are named after their parent so they never
                # take a shared schema's name (e.g. `Example`).
                "--naming-strategy",
                "full-path",
                "--formatters",
                "ruff-format",
                "--disable-timestamp",
                "--custom-file-header",
                HEADER,
            ],
            check=True,
        )
    CLIENT_OUTPUT.write_text(render_client(spec))
    subprocess.run(["ruff", "format", str(CLIENT_OUTPUT)], check=True)


if __name__ == "__main__":
    sys.exit(main())
