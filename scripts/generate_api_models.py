"""Generates src/judgeval/internal/api/models.py from the committed public spec.

The spec (openapi/public-api.json, copied from judgment-mono's
packages/shared/public-api/openapi.json) names shared schemas in
`components.schemas`, which datamodel-codegen emits as named TypedDicts, e.g.
`ExampleEvaluationRun`. Inline bodies of `x-mcp` routes are named after their
MCP tool first, e.g. `CreateJudgeRequest`.

    uv run python scripts/generate_api_models.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "public-api.json"
OUTPUT = ROOT / "src" / "judgeval" / "internal" / "api" / "models.py"


def name_inline_bodies(spec: dict[str, Any]) -> dict[str, Any]:
    """Moves each x-mcp route's inline JSON request/200 body into
    components.schemas as `<Tool>Request` / `<Tool>Response`."""
    schemas = spec["components"]["schemas"]
    for operations in spec["paths"].values():
        for op in operations.values():
            if not isinstance(op, dict) or "x-mcp" not in op:
                continue
            tool = op["x-mcp"]["tool"].title().replace("_", "")
            bodies = {
                "Request": op.get("requestBody", {}),
                "Response": op["responses"].get("200", {}),
            }
            for suffix, body in bodies.items():
                content = body.get("content", {}).get("application/json")
                if content is None or "$ref" in content["schema"]:
                    continue
                name = tool + suffix
                if name in schemas:
                    raise SystemExit(f"{name} is already in components.schemas")
                schemas[name] = content["schema"]
                content["schema"] = {"$ref": f"#/components/schemas/{name}"}
    return spec


def main() -> None:
    spec = name_inline_bodies(json.loads(SPEC.read_text()))
    with tempfile.NamedTemporaryFile("w", suffix=".json") as named:
        json.dump(spec, named)
        named.flush()
        subprocess.run(
            [
                "datamodel-codegen",
                "--input",
                named.name,
                "--input-file-type",
                "openapi",
                "--output",
                str(OUTPUT),
                "--output-model-type",
                "typing.TypedDict",
                "--target-python-version",
                "3.10",
                "--use-standard-collections",
                "--use-union-operator",
                # Inline schemas are named after their parent so they never
                # take a shared schema's name (e.g. `Example`).
                "--naming-strategy",
                "full-path",
                "--formatters",
                "ruff-format",
                "--disable-timestamp",
                "--custom-file-header",
                "# Generated by scripts/generate_api_models.py from openapi/public-api.json.\n# DO NOT EDIT MANUALLY",
            ],
            check=True,
        )


if __name__ == "__main__":
    sys.exit(main())
